"""Generate the `/hotdog-rater` fill tables (src/discord/hotdog.rs: FILL,
LENGTH_FILL, GIRTH_FILL).

Without the fill band, `measure()` gives some printable sizes (0.1 cm steps,
2.5–40.0 cm long, 5.0–22.0 cm around) almost no chance: the far tails of the
normal bell. The fill band tops every value up to FLOOR × the most likely
value's chance. This computes the normal group's distribution exactly (Irwin–Hall
CDFs, the clamps, the rounding), solves for the band's width and prints the
Rust constants. Run it after changing any constant in `measure()`:

    python3 tools/hotdog-fill/gen.py
"""
from math import comb, factorial, floor

FLOOR = 0.10   # least chance of any value, as a fraction of the most likely value's
SCALE = 1_000_000_000  # table weights: parts per billion of the band

def ih_cdf(s):
    """P(sum of 12 uniforms <= s)."""
    if s <= 0: return 0.0
    if s >= 12: return 1.0
    if s > 6: return 1.0 - ih_cdf(12 - s)
    return sum((-1) ** k * comb(12, k) * (s - k) ** 12 for k in range(floor(s) + 1)) / factorial(12)

def ih_pdf(s):
    if s <= 0 or s >= 12: return 0.0
    if s > 6: s = 12 - s
    return sum((-1) ** k * comb(12, k) * (s - k) ** 11 for k in range(floor(s) + 1)) / factorial(11)

def z_cdf(t): return ih_cdf(t + 6)          # Stream::normal

# girth_z = 0.6 z1 + 0.8 z2: P(gz <= t) = ∫ f(a) P(z2 <= (t - 0.6a)/0.8) da, Simpson per 1/40.
STEPS = 12 * 40
H = 12 / STEPS
GRID = [(-6 + i * H, ih_pdf(i * H) * (1 if i in (0, STEPS) else 4 if i % 2 else 2)) for i in range(STEPS + 1)]
def gz_cdf(t): return sum(w * z_cdf((t - 0.6 * a) / 0.8) for a, w in GRID) * H / 3

def clamped(cdf, mean, sd, lo, hi):
    """{tenths: P} for round1(clamp(mean + sd·z, lo, hi))."""
    c = lambda x: cdf((x - mean) / sd)
    out = {}
    for v in range(round(lo * 10), round(hi * 10) + 1):
        a = 0.0 if v == round(lo * 10) else c((v - 0.5) / 10)
        b = 1.0 if v == round(hi * 10) else c((v + 0.5) / 10)
        out[v] = b - a
    return out

def mix(parts, lo, hi):
    return {v: sum(w * d.get(v, 0.0) for w, d in parts) for v in range(lo, hi + 1)}

L_NORMAL = clamped(z_cdf, 13.5, 2.8, 2.5, 40.0)
G_NORMAL = clamped(gz_cdf, 11.7, 1.6, 5.0, 22.0)

def base(w):
    l = mix([(1 - w, L_NORMAL)], 25, 400)
    g = mix([(1 - w, G_NORMAL)], 50, 220)
    return l, g

def shortfall(d, c): return {v: c - p for v, p in d.items() if p < c}

def level_for(d, w):
    """The c with sum((c - p)+) = w."""
    lo, hi = 0.0, max(d.values())
    for _ in range(200):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if sum(max(0.0, mid - p) for p in d.values()) < w else (lo, mid)
    return hi

# measure() uses one draw for both tables, pairing their short and long ends
# (below / above the peaks): a short fill hotdog is a thin one, a long one
# thick. So each end of the band is as big as the measure that needs more
# there; the other measure's end then fills a little above the floor. The
# peaks shrink as the band grows, so iterate; then round the band up.
L_SPLIT, G_SPLIT = 135, 117
def split(d, at): return ({v: p for v, p in d.items() if v < at}, {v: p for v, p in d.items() if v >= at})
def need(d, c): return sum(shortfall(d, c).values())
def ends(w):
    l, g = base(w)
    (l_lo, l_hi), (g_lo, g_hi) = split(l, L_SPLIT), split(g, G_SPLIT)
    cl, cg = FLOOR * max(l.values()), FLOOR * max(g.values())
    return max(need(l_lo, cl), need(g_lo, cg)), max(need(l_hi, cl), need(g_hi, cg))
w = 0.2
for _ in range(200):
    lo, hi = ends(w)
    w = lo + hi
w = -(-w * 10_000 // 1) / 10_000
lo, hi = ends(w)
hi = w - lo   # the rounding goes to the long end
l, g = base(w)
def fill(d, at):
    a, b = split(d, at)
    return {**shortfall(a, level_for(a, lo)), **shortfall(b, level_for(b, hi))}
lf, gf = fill(l, L_SPLIT), fill(g, G_SPLIT)
pl = {v: p + lf.get(v, 0.0) for v, p in l.items()}
pg = {v: p + gf.get(v, 0.0) for v, p in g.items()}

def table(name, f):
    rows = [(v, round(x / w * SCALE)) for v, x in sorted(f.items()) if round(x / w * SCALE) > 0]
    body = "\n".join("    " + " ".join(f"({v}, {n})," for v, n in rows[i:i + 6]) for i in range(0, len(rows), 6))
    return f"const {name}: [(u16, u32); {len(rows)}] = [\n{body}\n];"

print(f"// Generated by tools/hotdog-fill/gen.py (FLOOR = {FLOOR}): floor {min(pl.values()) / max(pl.values()):.4f}"
      f" of peak for length, {min(pg.values()) / max(pg.values()):.4f} for girth.")
print(f"const FILL: f64 = {w};")
print(table("LENGTH_FILL", lf))
print(table("GIRTH_FILL", gf))
print(f"# length peak {max(pl.values()):.6f} at {max(pl, key=pl.get) / 10}, min {min(pl.values()):.6f};"
      f" girth peak {max(pg.values()):.6f} at {max(pg, key=pg.get) / 10}, min {min(pg.values()):.6f}", flush=True)
import sys
tiers = [(0, 70), (70, 110), (110, 150), (150, 190), (190, 260), (260, 401)]
print("# tiers " + " ".join(f"{sum(p for v, p in pl.items() if a <= v < b) * 100:.2f}%" for a, b in tiers), file=sys.stderr)
